"""Writes library/CATALOGUE.md: every slide in the component library, what it is for, and its full spec,
so a deck can be planned from the brief and each slide copied with "from": <id> and new words.

    python3 tools/catalogue.py
"""
import os as _os
GCW = _os.path.dirname(_os.path.dirname(_os.path.abspath(__file__))) + "/"
import sys, json
sys.path.insert(0, GCW + "tools"); sys.path.insert(0, GCW + "library")
import specs

USE = {
    "cover": "Open the deck. Three ribbon lines (about 12 characters each), a [label] and a month.",
    "contents": "The agenda, after the cover. Up to five items.",
    "divider": "Open a chapter: 'Part One' plus a two-line title. Sets the chapter colour.",
    "statement": "Land one message: headline, standfirst and a short paragraph, with drinks art on the right.",
    "fullphoto": "A full-bleed photo with two or three big lines. A breather between busy slides.",
    "steps": "A process or next steps, in order. 3, 4, 2x2, 3x2 or 3+2 numbered panels on full colour.",
    "icons": "3 to 6 reasons, benefits or features, each with an icon, on full colour.",
    "jcards": "What a guide, offer or service includes: 3, 4 or 2x2 numbered cards.",
    "table": "Specs or a range, full width.",
    "table_side": "A table on the right with a paragraph on the left.",
    "photo": "A photo on the left, words and points on the right.",
    "challenges": "The problems a buyer faces, as numbered bars (wide, text only or with a photo).",
    "timeline": "Stages with timings, such as idea to shelf.",
    "problemfix": "Problem on the left, our fix on the right, 3 or 5 rows.",
    "facts": "Three headline facts that prove a point.",
    "retail": "Retailer logos: proof on shelf.",
    "certs": "Certifications (white or on colour).",
    "bigicons": "Big icon circles for 4 or 5 customer problems or groups.",
    "statcards": "Market figures where the number is the story: 3 or 4 cards with the figure in a yellow pill.",
    "casestudy": "A customer success study: challenge, our solution, the result, with a photo.",
    "global": "Where we sell: the world map with fact cards.",
    "page": "A rebuilt page from the Carlsberg or Tesco decks (categories, no and low, functional, building blocks, range, the magic, base pages 14 to 17, solutions). Use as they are.",
    "routes": "Ways we help, as the website's route cards (new drink, fix a problem and so on).",
    "who": "Who we work with, as large icon circles.",
    "compare": "Us against the alternatives, our column in yellow.",
    "chart": "A bar chart: ink bars, the key bar in yellow, live labels.",
    "supply": "Ordering and supply: the website fact sheet.",
    "close": "The last slide. Always the same.",
    "mphoto": "Master template: photo on one half, words on the other.",
    "mhalves": "Master template: light half with words, dark half with points under the swirl.",
    "mdrinks": "Master template: words left, drinks art right.",
    "mband": "Master template: headline over a dark band of facts, drinks crossing the seam.",
    "mbottles": "Master template: words with bottles art.",
}

lines = ["# Component library", "", "Every slide a deck may use. Start each slide with `{\"from\": \"<id>\"}` and change only the words, "
         "`chapter`, `photo` or `sw` (swirl: 99, 6, 7 or 8). Generated by `tools/catalogue.py`; do not edit by hand.", ""]
seen = []
Q = json.load(open(GCW + "library/grounds.json"))
for s in specs.COMPONENTS["slides"]:
    if s["r"] not in seen: seen.append(s["r"])
for r in seen:
    group = [s for s in specs.COMPONENTS["slides"] if s["r"] == r]
    lines += [f"## {r}", "", USE.get(r, ""), ""]
    for s in group:
        lines += [f"### {s['id']}" + ("  (quiet: white, cream or photo ground)" if Q.get(s["id"]) == "quiet" else ""), "```json", json.dumps({k: v for k, v in s.items() if k != "r"}, ensure_ascii=False), "```", ""]
photos = sorted(f[:-4] for f in _os.listdir(GCW + "plates/photos") if f.endswith(".jpg") and not f.startswith("full-"))
pp = sorted(f[:-4] for f in _os.listdir(GCW + "plates/photoplates") if f.endswith(".jpg"))
full = sorted(f[5:-4] for f in _os.listdir(GCW + "plates/photos") if f.startswith("full-"))
lines += ["## Photos", "",
          "- `mphoto`, `casestudy` and `challenges` (chal-photo) take any photo in `plates/photos/`: " + ", ".join(photos) + ".",
          "  A new photo goes in `plates/photos/<name>.jpg` (landscape, about 1920px wide, under 400KB), then `photo: <name>`.",
          "- `photo` slides have the photo set into Jim's ring background, so only these: " + ", ".join(pp) + ".",
          "- `fullphoto` uses `plates/photos/full-<name>.jpg`: " + ", ".join(full) + ".", ""]
REPO = GCW
icons = sorted(f[3:-5] for f in _os.listdir(REPO + "public/gc/img/concepts") if f.startswith("ic-") and f.endswith(".webp"))
lines += ["## Icons", "", "For icon rows (the third item of each point): look at `library/icons.png` to choose. " + ", ".join(icons) + ".", ""]
open(GCW + "library/CATALOGUE.md", "w").write("\n".join(lines))
print("wrote library/CATALOGUE.md", len(specs.COMPONENTS["slides"]), "slides")
